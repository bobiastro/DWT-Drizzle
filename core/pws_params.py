# DWT 叠加软件：参数的唯一真源
#
# 一份定义，三处消费：
#   · 界面控件由 PARAMS 生成（标签、范围、默认值、悬停说明都取自这里）
#   · 引擎由 PwsParams 数据类读取
#   · 命令行入口由 PARAMS 生成 argparse
# 改一个默认值或一句说明只改这一处 —— 界面与引擎不可能漂移。

from __future__ import annotations

from dataclasses import dataclass, fields
from typing import Tuple

# 参数表版本号：改动默认值时同步修改，界面下次启动会一次性把持久化的参数
#   刷成新的默认值（否则本机旧会话会一直沿用保存过的旧值）。
PARAMS_VER = '1.0'


@dataclass(frozen=True)
class Param:
    """一个参数的完整描述（界面与命令行都由它生成）"""

    key: str                      # 同时是 PwsParams 的字段名与命令行 --key
    label: str                    # 界面标签
    kind: str                     # dir / text / float / int / choice / check
    group: str                    # 基础 / 标准 / 高级
    desc: str                     # 用途（一句话）
    usage: str                    # 取值与影响
    lo: float = 0.0
    hi: float = 0.0
    step: float = 1.0
    dec: int = 2                  # 小数位
    unit: str = ''
    choices: Tuple[Tuple[str, object], ...] = ()   # ((界面文字, 值), …)


